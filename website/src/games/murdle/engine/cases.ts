/** The books, in the order the list shows them - a new book goes on the end. */
export const SERIES_ORDER: readonly Series[] = ["volume1"];

/** Words a title may start with that its place in the alphabet ignores. */
const ARTICLES = /^(der|die|das|ein|eine)\s+/i;

/** The difficulties, easiest first - the parts of the book. */
export const DIFFICULTY_ORDER: readonly Difficulty[] = [
  "tutorial",
  "elementary",
  "occult",
  "hardBoiled",
  "impossible",
];

/**
 * A case by its id.
 *
 * @param id - the case's id
 * @returns it, or null when there is none
 */
export function caseById(id: string): Case | null {
  return CASES.find((one) => one.id === id) ?? null;
}

/**
 * The cases before and after one, in the book's order.
 *
 * @param kase - the case
 * @returns the one before and the one after - either may be missing
 */
export function neighboursOf(
  kase: Case,
): readonly [Case | undefined, Case | undefined] {
  const at = CASES.findIndex((one) => one.id === kase.id);
  return [CASES[at - 1], CASES[at + 1]];
}

/**
 * The order of the list within a book: by number, the tutorial first.
 *
 * @param left - one case
 * @param right - the other
 * @returns negative when left comes first
 */
export function inOrder(left: Case, right: Case): number {
  return (
    SERIES_ORDER.indexOf(left.series) - SERIES_ORDER.indexOf(right.series) ||
    (left.number ?? 0) - (right.number ?? 0)
  );
}

/**
 * The order of search hits: alphabetical by title, without its article.
 *
 * @param left - one case
 * @param right - the other
 * @returns negative when left comes first
 */
export function byName(left: Case, right: Case): number {
  return sortName(left).localeCompare(sortName(right), "de");
}

/**
 * A title as the alphabet sees it.
 */
function sortName(kase: Case): string {
  return kase.title.replace(ARTICLES, "");
}
