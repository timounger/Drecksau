/** Every fighter id, for checking what comes off the wire. */
export const CHARACTER_IDS: readonly CharacterId[] = CHARACTERS.map(
  (character) => character.id,
);

/** Every ability id, for checking what comes off the wire. */
export const ABILITY_IDS: readonly AbilityId[] = Object.keys(
  ABILITIES,
) as AbilityId[];

/**
 * Looks a fighter up.
 *
 * @param id - the fighter
 * @returns its definition
 */
export function characterById(id: CharacterId): CharacterDef {
  return CHARACTERS.find((entry) => entry.id === id) ?? CHARACTERS[0];
}

/**
 * What a throw sends flying.
 *
 * @param character - the fighter
 * @param ability - the ability used with it, if any
 * @returns the item thrown
 */
export function itemFor(
  character: CharacterDef,
  ability: AbilityId | null,
): ItemDef {
  const override = ability === null ? undefined : ABILITIES[ability].item;
  return ITEMS[override ?? character.item];
}

/**
 * Builds one item entry - positional, so the table above stays one line each.
 *
 * @returns the item definition
 */
function item(
  id: ItemId,
  name: string,
  damage: number,
  radius: number,
  windFactor: number,
  gravityFactor: number,
  speedFactor: number,
  behavior: ItemDef["behavior"],
  look: ItemDef["look"],
  color: string,
  sticky: boolean,
  spin: number,
): ItemDef {
  return {
    id,
    name,
    damage,
    radius,
    windFactor,
    gravityFactor,
    speedFactor,
    behavior,
    look,
    color,
    sticky,
    spin,
  };
}
