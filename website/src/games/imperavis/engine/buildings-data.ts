/**
 * Decorations and how much each lifts the satisfaction of houses in its
 * reach (a share, 0.05 = +5 points). Different kinds in reach add up, the
 * same kind twice counts once, and the sum is capped by {@link DECOR_CAP}.
 */
export const DECOR_BEAUTY: Readonly<Partial<Record<BuildingKind, number>>> = {
  decorTree: 0.02,
  flowerBed: 0.02,
  lantern: 0.02,
  plaza: 0.03,
  park: 0.05,
  fountain: 0.05,
  statue: 0.06,
};

/** The decoration kinds. */
export const DECOR_KINDS: readonly BuildingKind[] = Object.keys(
  DECOR_BEAUTY,
) as BuildingKind[];

/** Most satisfaction decorations can add to one house. */
export const DECOR_CAP = 0.15;

/** Kinds that can be raised to a second stage. */
export const LEVEL_KINDS: readonly BuildingKind[] = BUILDINGS.filter(
  (def) =>
    def.recipe !== null ||
    def.kind === "kontor" ||
    def.kind === "warehouse" ||
    def.science > 0,
).map((def) => def.kind);

/** The second stage works this much faster (producers and scholars). */
export const LEVEL_SPEED = 1.5;

/** The second stage of a store holds this much more and sends one cart more. */
export const LEVEL_STORAGE = 1.5;

/** The second stage costs this much more upkeep. */
export const LEVEL_UPKEEP = 1.5;

/** Goods the second stage costs. */
export const LEVEL_COST = { bricks: 6, tools: 3 } as const;

/** Share of the building's own gold price the second stage costs. */
export const LEVEL_GOLD = 0.75;

/** Units a producer can hold of its output before it stops. */
export const OUTPUT_CAPACITY = 6;

/** Units of each input a producer keeps at most. */
export const INPUT_CAPACITY = 4;

/** Kinds open from the start. */
export const STARTING_UNLOCKS: readonly BuildingKind[] = BUILDINGS.filter(
  (def) => def.unlock === null && def.research === null,
).map((def) => def.kind);

/**
 * Hit points of a building by its footprint.
 *
 * @param size - width and depth in tiles
 * @returns hit points
 */
function siteHp(size: { w: number; h: number }): number {
  return BASE_HP + HP_PER_TILE * size.w * size.h;
}
